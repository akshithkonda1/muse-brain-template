#!/usr/bin/env python3
"""scan.py — the one scan command for Muse Brain (a plain-Markdown second brain).

Template version: no personal data, no repo home assumed.

Walks notes/, extracts tags (#tag) and [[wiki-links]], and regenerates
MAP.md (index by tag, link-graph summary, stats) and dashboard.html
(note tree by tag, counts, recent notes).

Stdlib only. Run from the brain folder:

    python3 scan.py

Outputs are overwritten each run. MAP.md is generated — never edit by hand.
"""

import html
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

BRAIN = Path(__file__).resolve().parent
NOTES_DIR = BRAIN / "notes"
MAP_PATH = BRAIN / "MAP.md"
DASH_PATH = BRAIN / "dashboard.html"

CANONICAL_TAGS = [
    "brain", "notes", "projects", "journal",
    "people", "places", "ideas", "goals", "money",
]

TAG_RE = re.compile(r"#([A-Za-z][A-Za-z0-9_-]*)")
LINK_RE = re.compile(r"\[\[([^\]|#]+)(?:#[^\]]*)?(?:\|[^\]]*)?\]\]")
TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)


def normalize_target(raw: str) -> str:
    """Normalize a [[link]] target to a notes/ filename stem."""
    target = raw.strip().lower().replace(" ", "-")
    return target


def scan_notes():
    """Read every note; return list of dicts with title/tags/links/mtime."""
    notes = []
    for path in sorted(NOTES_DIR.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        title_match = TITLE_RE.search(text)
        title = title_match.group(1) if title_match else path.stem
        tags = sorted(set(TAG_RE.findall(text)))
        raw_links = LINK_RE.findall(text)
        links = sorted(set(normalize_target(t) for t in raw_links))
        notes.append({
            "stem": path.stem,
            "file": path.name,
            "title": title,
            "tags": tags,
            "links": links,
            "mtime": path.stat().st_mtime,
        })
    return notes


def build_graph(notes):
    """Incoming links per stem; broken links; orphans."""
    stems = {n["stem"] for n in notes}
    incoming = defaultdict(list)
    broken = []
    for note in notes:
        for target in note["links"]:
            if target in stems:
                incoming[target].append(note["stem"])
            else:
                broken.append((note["stem"], target))
    orphans = [
        n["stem"] for n in notes
        if not n["links"] and not incoming.get(n["stem"])
    ]
    return incoming, sorted(set(broken)), sorted(orphans)


def render_map(notes, tag_counts, incoming, broken, orphans, now):
    """Render MAP.md."""
    total_links = sum(len(n["links"]) for n in notes)
    lines = []
    lines.append("# MAP — index of the brain")
    lines.append("")
    lines.append(f"_Generated by `scan.py` on {now}. Do not edit by hand — "
                 "re-run `python3 scan.py`._")
    lines.append("")
    lines.append("## Stats")
    lines.append("")
    lines.append(f"- Notes: **{len(notes)}**")
    lines.append(f"- Links: **{total_links}** "
                 f"({sum(len(v) for v in incoming.values())} resolved, "
                 f"{len(broken)} broken)")
    lines.append(f"- Orphans (no links in or out): **{len(orphans)}**")
    lines.append("")
    lines.append("| Tag | Notes |")
    lines.append("| --- | ---: |")
    for tag in CANONICAL_TAGS:
        lines.append(f"| #{tag} | {tag_counts.get(tag, 0)} |")
    other_tags = sorted(
        t for t in tag_counts if t not in CANONICAL_TAGS
    )
    for tag in other_tags:
        lines.append(f"| #{tag} (non-canonical) | {tag_counts[tag]} |")
    lines.append("")
    lines.append("## Index by tag")
    lines.append("")
    by_tag = defaultdict(list)
    for note in notes:
        for tag in note["tags"]:
            by_tag[tag].append(note)
    for tag in CANONICAL_TAGS + other_tags:
        tagged = by_tag.get(tag, [])
        if not tagged:
            continue
        lines.append(f"### #{tag} ({len(tagged)})")
        lines.append("")
        for note in tagged:
            lines.append(f"- [{note['title']}](notes/{note['file']})")
        lines.append("")
    lines.append("## Link graph")
    lines.append("")
    lines.append("Most-linked notes (linked from the most other notes):")
    lines.append("")
    ranked = sorted(
        notes, key=lambda n: len(incoming.get(n["stem"], [])), reverse=True
    )
    for note in ranked[:10]:
        count = len(incoming.get(note["stem"], []))
        if count == 0:
            break
        lines.append(f"- [{note['title']}](notes/{note['file']}) — "
                     f"{count} incoming, {len(note['links'])} outgoing")
    lines.append("")
    if orphans:
        lines.append("### Orphans")
        lines.append("")
        for stem in orphans:
            note = next(n for n in notes if n["stem"] == stem)
            lines.append(f"- [{note['title']}](notes/{note['file']})")
        lines.append("")
    if broken:
        lines.append("### Broken links")
        lines.append("")
        for source, target in broken:
            lines.append(f"- `{source}` links to `[[{target}]]` — "
                         "no such note")
        lines.append("")
    lines.append("## All notes")
    lines.append("")
    for note in notes:
        tags = " ".join(f"#{t}" for t in note["tags"])
        lines.append(f"- [{note['title']}](notes/{note['file']}) {tags}")
    lines.append("")
    return "\n".join(lines)


def render_dashboard(notes, tag_counts, incoming, broken, orphans, now):
    """Render a simple dashboard.html — inline CSS only, no external assets."""
    total_links = sum(len(n["links"]) for n in notes)
    max_tag = max(tag_counts.values()) if tag_counts else 1
    recent = sorted(notes, key=lambda n: n["mtime"], reverse=True)[:8]

    def esc(s):
        return html.escape(str(s))

    parts = []
    parts.append("<!DOCTYPE html>")
    parts.append("<html lang=\"en\"><head><meta charset=\"utf-8\">")
    parts.append("<meta name=\"viewport\" content=\"width=device-width, "
                 "initial-scale=1\">")
    parts.append("<title>Muse Brain — Dashboard</title>")
    parts.append("<style>")
    parts.append("body{font-family:system-ui,sans-serif;max-width:900px;"
                 "margin:2rem auto;padding:0 1rem;color:#1c1c1e;"
                 "background:#fafafa}")
    parts.append("h1{font-size:1.6rem}h2{font-size:1.2rem;"
                 "border-bottom:1px solid #ddd;padding-bottom:.25rem}")
    parts.append(".cards{display:flex;gap:1rem;flex-wrap:wrap}")
    parts.append(".card{flex:1;min-width:140px;background:#fff;border:1px "
                 "solid #e0e0e0;border-radius:8px;padding:1rem}")
    parts.append(".card b{font-size:1.6rem;display:block}")
    parts.append(".bar-row{display:flex;align-items:center;gap:.5rem;"
                 "margin:.25rem 0}")
    parts.append(".bar-row span{width:90px}")
    parts.append(".bar{height:14px;background:#7c5cbf;border-radius:3px}")
    parts.append("ul{line-height:1.6}")
    parts.append(".meta{color:#666;font-size:.9rem}")
    parts.append("</style></head><body>")
    parts.append("<h1>Muse Brain — Dashboard</h1>")
    parts.append(f"<p class=\"meta\">Generated by scan.py on {esc(now)}. "
                 "Plain folder of Markdown notes; no external assets.</p>")
    parts.append("<div class=\"cards\">")
    parts.append(f"<div class=\"card\"><b>{len(notes)}</b>notes</div>")
    parts.append(f"<div class=\"card\"><b>{total_links}</b>links</div>")
    parts.append(f"<div class=\"card\"><b>{len(broken)}</b>broken "
                 "links</div>")
    parts.append(f"<div class=\"card\"><b>{len(orphans)}</b>orphans</div>")
    parts.append("</div>")

    parts.append("<h2>Notes by tag</h2>")
    for tag in CANONICAL_TAGS:
        count = tag_counts.get(tag, 0)
        width = int(count / max_tag * 100) if max_tag else 0
        parts.append(f"<div class=\"bar-row\"><span>#{esc(tag)}</span>"
                     f"<div class=\"bar\" style=\"width:{width}%\"></div>"
                     f"{count}</div>")

    by_tag = defaultdict(list)
    for note in notes:
        for tag in note["tags"]:
            by_tag[tag].append(note)
    parts.append("<h2>Note tree by tag</h2>")
    for tag in CANONICAL_TAGS:
        tagged = by_tag.get(tag, [])
        if not tagged:
            continue
        parts.append(f"<h3>#{esc(tag)} ({len(tagged)})</h3><ul>")
        for note in tagged:
            parts.append(f"<li>{esc(note['title'])} "
                         f"<span class=\"meta\">({esc(note['file'])})"
                         "</span></li>")
        parts.append("</ul>")

    parts.append("<h2>Recent notes</h2><ul>")
    for note in recent:
        when = datetime.fromtimestamp(
            note["mtime"], tz=timezone.utc).strftime("%Y-%m-%d")
        parts.append(f"<li>{esc(note['title'])} "
                     f"<span class=\"meta\">— {when}</span></li>")
    parts.append("</ul>")

    if orphans:
        parts.append("<h2>Orphans</h2><ul>")
        for stem in orphans:
            note = next(n for n in notes if n["stem"] == stem)
            parts.append(f"<li>{esc(note['title'])}</li>")
        parts.append("</ul>")
    if broken:
        parts.append("<h2>Broken links</h2><ul>")
        for source, target in broken:
            parts.append(f"<li>{esc(source)} → "
                         f"[[{esc(target)}]] (no such note)</li>")
        parts.append("</ul>")

    parts.append("</body></html>")
    return "\n".join(parts)


def main() -> int:
    if not NOTES_DIR.is_dir():
        print(f"notes/ not found under {BRAIN}", file=sys.stderr)
        return 1
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    notes = scan_notes()
    tag_counts = Counter()
    for note in notes:
        tag_counts.update(note["tags"])
    incoming, broken, orphans = build_graph(notes)

    MAP_PATH.write_text(
        render_map(notes, tag_counts, incoming, broken, orphans, now),
        encoding="utf-8",
    )
    DASH_PATH.write_text(
        render_dashboard(notes, tag_counts, incoming, broken, orphans, now),
        encoding="utf-8",
    )

    total_links = sum(len(n["links"]) for n in notes)
    print(f"Scanned {len(notes)} notes, {total_links} links.")
    print("Tags: " + ", ".join(
        f"#{t}={tag_counts.get(t, 0)}" for t in CANONICAL_TAGS
    ))
    non_canonical = sorted(t for t in tag_counts if t not in CANONICAL_TAGS)
    if non_canonical:
        print("Non-canonical tags found: " +
              ", ".join(f"#{t}" for t in non_canonical))
    print(f"Broken links: {len(broken)}; orphans: {len(orphans)}.")
    if broken:
        for source, target in broken:
            print(f"  BROKEN: {source} -> [[{target}]]")
    if orphans:
        for stem in orphans:
            print(f"  ORPHAN: {stem}")
    print(f"Wrote {MAP_PATH.name} and {DASH_PATH.name}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
