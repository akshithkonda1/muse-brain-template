#!/usr/bin/env python3
"""scan.py — the one scan command for Muse Brain (a plain-Markdown second brain).

Template version: no personal data, no repo home assumed.

Walks notes/, extracts tags (#tag) and [[wiki-links]], and regenerates
MAP.md (index by tag, link-graph summary, stats) and dashboard.html
(note tree by tag, counts, recent notes).

Stdlib only. Run from ~/workspace/brain/:

    python3 scan.py

Outputs are overwritten each run. MAP.md is generated — never edit by hand.
"""

import html
import json
import math
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

BRAIN = Path(__file__).resolve().parent
NOTES_DIR = BRAIN / "notes"
MAP_PATH = BRAIN / "MAP.md"
DASH_PATH = BRAIN / "dashboard.html"

CANONICAL_TAGS = [
    "brain", "notes", "projects", "journal",
    "people", "places", "ideas", "goals", "money",
]

TAG_RE = re.compile(r"#([A-Za-z][A-Za-z0-9_-]*)")
LINK_RE = re.compile(r"\[\[([^\]|#]+)(?:#[^\]]*)?(?:\|[^\]]*)?\]\]")
TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)


def normalize_target(raw: str) -> str:
    """Normalize a [[link]] target to a notes/ filename stem."""
    target = raw.strip().lower().replace(" ", "-")
    return target


def scan_notes():
    """Read every note; return list of dicts with title/tags/links/mtime."""
    notes = []
    for path in sorted(NOTES_DIR.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        title_match = TITLE_RE.search(text)
        title = title_match.group(1) if title_match else path.stem
        tags = sorted(set(TAG_RE.findall(text)))
        raw_links = LINK_RE.findall(text)
        links = sorted(set(normalize_target(t) for t in raw_links))
        notes.append({
            "stem": path.stem,
            "file": path.name,
            "title": title,
            "tags": tags,
            "links": links,
            "mtime": path.stat().st_mtime,
        })
    return notes


def build_graph(notes):
    """Incoming links per stem; broken links; orphans."""
    stems = {n["stem"] for n in notes}
    incoming = defaultdict(list)
    broken = []
    for note in notes:
        for target in note["links"]:
            if target in stems:
                incoming[target].append(note["stem"])
            else:
                broken.append((note["stem"], target))
    orphans = [
        n["stem"] for n in notes
        if not n["links"] and not incoming.get(n["stem"])
    ]
    return incoming, sorted(set(broken)), sorted(orphans)


def render_map(notes, tag_counts, incoming, broken, orphans, now):
    """Render MAP.md."""
    total_links = sum(len(n["links"]) for n in notes)
    lines = []
    lines.append("# MAP — index of the brain")
    lines.append("")
    lines.append(f"_Generated by `scan.py` on {now}. Do not edit by hand — "
                 "re-run `python3 scan.py`._")
    lines.append("")
    lines.append("## Stats")
    lines.append("")
    lines.append(f"- Notes: **{len(notes)}**")
    lines.append(f"- Links: **{total_links}** "
                 f"({sum(len(v) for v in incoming.values())} resolved, "
                 f"{len(broken)} broken)")
    lines.append(f"- Orphans (no links in or out): **{len(orphans)}**")
    lines.append("")
    lines.append("| Tag | Notes |")
    lines.append("| --- | ---: |")
    for tag in CANONICAL_TAGS:
        lines.append(f"| #{tag} | {tag_counts.get(tag, 0)} |")
    other_tags = sorted(
        t for t in tag_counts if t not in CANONICAL_TAGS
    )
    for tag in other_tags:
        lines.append(f"| #{tag} (non-canonical) | {tag_counts[tag]} |")
    lines.append("")
    lines.append("## Index by tag")
    lines.append("")
    by_tag = defaultdict(list)
    for note in notes:
        for tag in note["tags"]:
            by_tag[tag].append(note)
    for tag in CANONICAL_TAGS + other_tags:
        tagged = by_tag.get(tag, [])
        if not tagged:
            continue
        lines.append(f"### #{tag} ({len(tagged)})")
        lines.append("")
        for note in tagged:
            lines.append(f"- [{note['title']}](notes/{note['file']})")
        lines.append("")
    lines.append("## Link graph")
    lines.append("")
    lines.append("Most-linked notes (linked from the most other notes):")
    lines.append("")
    ranked = sorted(
        notes, key=lambda n: len(incoming.get(n["stem"], [])), reverse=True
    )
    for note in ranked[:10]:
        count = len(incoming.get(note["stem"], []))
        if count == 0:
            break
        lines.append(f"- [{note['title']}](notes/{note['file']}) — "
                     f"{count} incoming, {len(note['links'])} outgoing")
    lines.append("")
    if orphans:
        lines.append("### Orphans")
        lines.append("")
        for stem in orphans:
            note = next(n for n in notes if n["stem"] == stem)
            lines.append(f"- [{note['title']}](notes/{note['file']})")
        lines.append("")
    if broken:
        lines.append("### Broken links")
        lines.append("")
        for source, target in broken:
            lines.append(f"- `{source}` links to `[[{target}]]` — "
                         "no such note")
        lines.append("")
    lines.append("## All notes")
    lines.append("")
    for note in notes:
        tags = " ".join(f"#{t}" for t in note["tags"])
        lines.append(f"- [{note['title']}](notes/{note['file']}) {tags}")
    lines.append("")
    return "\n".join(lines)


def build_search_data(notes):
    """BM25 index data for the dashboard: idf, per-doc term counts, avgdl.

    Reuses ml/search.py when importable so the browser ranking matches
    the Python tool exactly; falls back to a small local computation.
    """
    docs = []
    for folder in ("notes", "wiki"):
        d = BRAIN / folder
        if not d.is_dir():
            continue
        for path in sorted(d.glob("*.md")):
            if path.name == "README.md":
                continue
            text = path.read_text(encoding="utf-8", errors="ignore")
            title_m = TITLE_RE.search(text)
            docs.append({
                "stem": path.stem,
                "file": str(path.relative_to(BRAIN)),
                "title": title_m.group(1) if title_m else path.stem,
                "tags": sorted(set(TAG_RE.findall(text))),
                "links": sorted({normalize_target(t) for t in LINK_RE.findall(text)}),
                "text": text,
                "mtime": path.stat().st_mtime,
            })
    try:
        sys.path.insert(0, str(BRAIN))
        from ml.search import Index, tokenize as ml_tokenize

        class _Doc(dict):
            pass

        ml_docs = []
        for d in docs:
            md = _Doc(d)
            md["tokens"] = ml_tokenize(d["text"])
            ml_docs.append(md)
        idx = Index(ml_docs)
        terms = {}
        for d in ml_docs:
            terms[d["stem"]] = {t: c for t, c in d["counts"].items()
                                if t in idx.idf}
        return {
            "docs": docs,
            "idf": {t: round(v, 4) for t, v in idx.idf.items()},
            "terms": terms,
            "avgdl": round(idx.avgdl, 2),
            "clusters": idx.clusters(),
            "suggest": [{"a": s["a"]["stem"], "b": s["b"]["stem"],
                         "cosine": s["cosine"],
                         "shared_tags": s["shared_tags"]}
                        for s in idx.suggest_links()],
            "duplicates": idx.duplicates(),
            "tensions": idx.conflicts(),
        }
    except Exception:
        # Fallback: plain term counts + idf, no clusters.
        import math as _math
        df = Counter()
        per_doc = {}
        for d in docs:
            toks = [w for w in re.findall(r"[a-z0-9']+",
                                          clean_text(d["text"]).lower())
                    if len(w) > 1]
            counts = Counter(toks)
            per_doc[d["stem"]] = dict(counts)
            for t in counts:
                df[t] += 1
        n = len(docs) or 1
        idf = {t: round(_math.log((n - c + 0.5) / (c + 0.5) + 1), 4)
               for t, c in df.items()}
        avgdl = sum(sum(c.values()) for c in per_doc.values()) / n
        return {"docs": docs, "idf": idf, "terms": per_doc,
                "avgdl": round(avgdl, 2), "clusters": [], "suggest": [],
                "duplicates": [], "tensions": []}


def clean_text(text: str) -> str:
    """Strip code fences / markdown markup; expand [[links]] to words."""
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = LINK_RE.sub(lambda m: " " + m.group(1).replace("-", " ") + " ", text)
    text = re.sub(r"[#*`>\[\]()|_]", " ", text)
    return text


def layout_positions(notes, incoming, clusters=None):
    """Deterministic, cluster-aware force layout for the graph view.

    Cluster centres sit on a ring; nodes seed around their own
    cluster's centre, then ~120 iterations of repulsion + link
    springs + a pull toward the cluster centre settle them. Seeded,
    so the same brain always draws the same map. Without clusters
    it falls back to grouping by first tag. Returns
    {stem: [x, y]} in an 800x520 viewBox.
    See docs/design-system.md for the visual rules this serves.
    """
    import random as _random

    rng = _random.Random(7)
    stems = [n["stem"] for n in notes]
    if not stems:
        return {}
    # stem -> cluster index (clusters arrive largest-first, so the
    # index is also the colour rank in docs/design-system.md).
    # Only clusters with 2+ members get their own territory — with
    # 24 clusters in a small brain, singletons would otherwise crowd
    # the ring until every hull overlaps every other. Singletons are
    # parked on the periphery, grouped by first tag.
    cluster_of = {}
    cluster_list = clusters or []
    major = [c for c in cluster_list if len(c.get("members", [])) >= 2]
    for ci, c in enumerate(cluster_list):
        if c not in major:
            continue
        for m in c.get("members", []):
            cluster_of[m] = ci
    if not cluster_list:
        groups = {}
        for n in notes:
            key = (n["tags"] or ["notes"])[0]
            groups.setdefault(key, []).append(n["stem"])
        for gi, key in enumerate(groups):
            for stem in groups[key]:
                cluster_of[stem] = gi
    # Peripheral groups for notes in no major cluster, keyed by tag.
    peripheral = {}
    for n in notes:
        if n["stem"] not in cluster_of:
            key = (n["tags"] or ["notes"])[0]
            peripheral.setdefault(key, []).append(n["stem"])
    group_order = [ci for ci in sorted({cluster_of[s] for s in cluster_of})]
    for gi, key in enumerate(sorted(peripheral)):
        for stem in peripheral[key]:
            cluster_of[stem] = 1000 + gi
    n_clusters = len(group_order) + len(peripheral)
    # Centre for a group: major clusters on the ring, peripheral
    # groups on a wider, fainter orbit.
    def _centre(ci):
        idx = group_order.index(ci) if ci in group_order else 0
        total = max(n_clusters, 1)
        base = (idx / total) * 2 * math.pi
        return (400 + 165 * math.cos(base), 260 + 135 * math.sin(base))
    pos = {}
    for i, stem in enumerate(stems):
        ci = cluster_of.get(stem, 0)
        if ci >= 1000:
            # Peripheral: further out, on the tag group's own arc.
            gi = ci - 1000
            base = ((len(group_order) + gi) / max(n_clusters, 1)) * 2 * math.pi
            cx, cy = 400 + 205 * math.cos(base), 260 + 165 * math.sin(base)
        else:
            cx, cy = _centre(ci)
        a = rng.uniform(0, 2 * math.pi)
        r = 28 + rng.uniform(0, 52)
        pos[stem] = [cx + r * math.cos(a), cy + r * 0.8 * math.sin(a)]
    edges = []
    for n in notes:
        for t in n["links"]:
            if t in pos and t != n["stem"]:
                edges.append((n["stem"], t))
    for _ in range(120):
        forces = {s: [0.0, 0.0] for s in stems}
        for i, a in enumerate(stems):
            for b in stems[i + 1:]:
                dx = pos[a][0] - pos[b][0]
                dy = pos[a][1] - pos[b][1]
                dist = max(20.0, math.hypot(dx, dy))
                f = 900.0 / (dist * dist)
                fx, fy = f * dx / dist, f * dy / dist
                forces[a][0] += fx
                forces[a][1] += fy
                forces[b][0] -= fx
                forces[b][1] -= fy
        for a, b in edges:
            dx = pos[b][0] - pos[a][0]
            dy = pos[b][1] - pos[a][1]
            dist = max(1.0, math.hypot(dx, dy))
            f = (dist - 90) * 0.02
            fx, fy = f * dx / dist, f * dy / dist
            forces[a][0] += fx
            forces[a][1] += fy
            forces[b][0] -= fx
            forces[b][1] -= fy
        for s in stems:
            ci = cluster_of.get(s, 0)
            if ci >= 1000:
                gi = ci - 1000
                base = ((len(group_order) + gi) / max(n_clusters, 1)) * 2 * math.pi
                ccx, ccy = 400 + 205 * math.cos(base), 260 + 165 * math.sin(base)
            else:
                ccx, ccy = _centre(ci)
            # Pull toward the cluster centre, plus a gentle centre pull.
            fx = (ccx - pos[s][0]) * 0.03 + (400 - pos[s][0]) * 0.005 + forces[s][0]
            fy = (ccy - pos[s][1]) * 0.03 + (260 - pos[s][1]) * 0.005 + forces[s][1]
            pos[s][0] = min(770, max(30, pos[s][0] + fx))
            pos[s][1] = min(490, max(30, pos[s][1] + fy))
    # De-overlap pass: node radius is 8 + min(8, degree), so two hubs
    # need ~36px between centres. The link springs pull hubs together;
    # push any overlapping pair apart (half the overlap each), up to
    # 25 passes, deterministic order.
    deg = {n["stem"]: len(n["links"]) + len(incoming.get(n["stem"], [])) for n in notes}
    for _ in range(25):
        moved = False
        for i, a in enumerate(stems):
            for b in stems[i + 1:]:
                need = 8 + min(8, deg.get(a, 0)) + 8 + min(8, deg.get(b, 0)) + 6
                dx = pos[b][0] - pos[a][0]
                dy = pos[b][1] - pos[a][1]
                d = math.hypot(dx, dy) or 0.01
                if d < need:
                    push = (need - d) / 2
                    ux, uy = dx / d, dy / d
                    pos[a][0] = min(770, max(30, pos[a][0] - ux * push))
                    pos[a][1] = min(490, max(30, pos[a][1] - uy * push))
                    pos[b][0] = min(770, max(30, pos[b][0] + ux * push))
                    pos[b][1] = min(490, max(30, pos[b][1] + uy * push))
                    moved = True
        if not moved:
            break
    return {s: [round(x, 1), round(y, 1)] for s, (x, y) in pos.items()}



