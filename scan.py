def _excerpt(text):
    """One-line summary of a note: first substantive paragraph.

    Notes wrap paragraphs across physical lines, so join lines until
    the first blank line — the first line alone is usually a clipped
    half-sentence.
    """
    para = []
    started = False
    for line in text.split("\n"):
        line = line.strip()
        if not line:
            if started:
                break
            continue
        if line.startswith("#") or line.startswith("Tags:"):
            continue
        if line.startswith(">"):
            continue
        started = True
        para.append(line)
    if not para:
        return ""
    line = re.sub(r"\[\[([^\]|#]+)(?:#[^\]]*)?(?:\|[^\]]*)?\]\]",
                  r"\1", " ".join(para))
    line = re.sub(r"[*_`]", "", line)
    return (line[:217] + "\u2026") if len(line) > 220 else line


def _sources(text):
    """Source trail for a note: `Source:` lines + `(per ...)` lines."""
    found = []
    for line in text.split("\n"):
        m = re.match(r"\s*(?:[-*]\s+)?(?:\*\*)?Source:(?:\*\*)?\s+(.+?)\s*$", line)
        if m:
            found.append(m.group(1).strip())
    for m in re.finditer(r"\(per\s+[^)]+\)", text):
        found.append(m.group(0))
    for m in re.finditer(r"\(Source:\s*[^)]+\)", text):
        found.append(m.group(0))
    # De-duplicate, keep order, cap at 3 — the trail, not the text.
    # Sources can wrap across lines in the note; flatten the whitespace
    # so a trail never breaks mid-line in the UI or the map.
    out = []
    for s in found:
        s = " ".join(str(s).split())
        if s not in out:
            out.append(s)
    return out[:3]


def build_knows(docs, incoming, clusters):
    """The "What Muse knows" payload: topics + areas + coverage.

    One entry per note/wiki page: title, excerpt, source trail,
    tags/area, degree, cluster, links. Areas group topics by tag.
    Everything here is derived from the real files on disk — no
    invented facts. Used by the dashboard, /api/knows, the Windows
    snapshot, and MEMORY-MAP.md's "What Muse knows" section.
    """
    cluster_of = {}
    for ci, c in enumerate(clusters or []):
        for m in c.get("members", []):
            cluster_of[m] = {"index": ci, "label": c.get("label", "")}
    topics = []
    for d in docs:
        stem = d["stem"]
        tags = d.get("tags", [])
        area_tag = tags[0] if tags else "notes"
        topics.append({
            "stem": stem,
            "title": d["title"],
            "tags": tags,
            "area": AREA_LABELS.get(area_tag, area_tag.title()),
            "area_tag": area_tag,
            "excerpt": _excerpt(d.get("text", "")),
            "sources": _sources(d.get("text", "")),
            "source_needed": "[source needed]" in d.get("text", ""),
            "degree": len(d.get("links", [])) + len(incoming.get(stem, [])),
            "links": d.get("links", []),
            "incoming": sorted(incoming.get(stem, [])),
            "cluster": cluster_of.get(stem),
        })
    topics.sort(key=lambda t: -t["degree"])
    areas = []
    for tag in sorted({t["area_tag"] for t in topics}):
        members = [t for t in topics if t["area_tag"] == tag]
        areas.append({
            "tag": tag,
            "label": AREA_LABELS.get(tag, tag.title()),
            "count": len(members),
            "with_source": sum(1 for t in members if t["sources"]),
            "topics": [t["stem"] for t in members[:8]],
        })
    areas.sort(key=lambda a: -a["count"])
    return {
        "topics": topics,
        "areas": areas,
        "coverage": {
            "total": len(topics),
            "with_source": sum(1 for t in topics if t["sources"]),
            "source_needed": sum(1 for t in topics if t["source_needed"]),
            "linked": sum(1 for t in topics if t["degree"] > 0),
            "quiet": sum(1 for t in topics if t["degree"] == 0),
        },
    }


def render_dashboard(notes, tag_counts, incoming, broken, orphans, now):
    """Render the polished dashboard.html from app/dashboard-template.html.

    Embeds the whole searchable brain as JSON: note texts, the BM25
    index, clusters, suggestions, orphans, stale flags, and precomputed
    graph positions. Fully offline — no external assets. Falls back
    to the simple generated dashboard if the template is missing.
    """
    template_path = BRAIN / "app" / "dashboard-template.html"
    if not template_path.exists():
        return _render_dashboard_simple(
            notes, tag_counts, incoming, broken, orphans, now)
    data = build_search_data(notes)
    docs = data["docs"]
    now_ts = datetime.now(timezone.utc).timestamp()
    stale = sorted(
        d["stem"] for d in docs
        if (now_ts - d["mtime"]) > 90 * 86400
    )
    brain_json = {
        "generated": now,
        "notes": [{
            "stem": d["stem"],
            "file": d["file"],
            "title": d["title"],
            "tags": d["tags"],
            "links": d["links"],
            "text": d["text"],
            "terms": data["terms"].get(d["stem"], {}),
            "docLen": sum(data["terms"].get(d["stem"], {}).values()) or 1,
        } for d in docs],
        "incoming": {k: sorted(v) for k, v in incoming.items()},
        "clusters": data["clusters"],
        "suggest": data["suggest"],
        "duplicates": data["duplicates"],
        "tensions": data["tensions"],
        "orphans": sorted(orphans),
        "stale": stale,
        "stats": {
            "notes": len(notes),
            "links": sum(len(n["links"]) for n in notes),
            "broken": len(broken),
        },
        "tagCounts": dict(tag_counts),
        "idf": data["idf"],
        "avgdl": data["avgdl"],
        "stop": ("a an the and or of to in on for with is are was were be by "
                 "at as it its this that these those from into over under "
                 "after before not no nor but if then than so such can could "
                 "will would should he she they we you i his her their our "
                 "your my me him them us what which who whom when where why "
                 "how all any both each few more most other some such only "
                 "own same too very just also").split(),
        "positions": layout_positions(docs, incoming, data["clusters"]),
        # Design system (docs/design-system.md): cluster colours are
        # assigned by cluster rank, largest first; node colour is its
        # cluster colour. Hubs are the most-connected notes.
        "clusterColors": ["#7C5CFF", "#14B8A6", "#F59E0B", "#F43F5E",
                          "#0EA5E9", "#10B981", "#F97316", "#6366F1"],
        "clusterIndex": {m: ci for ci, c in enumerate(data["clusters"])
                         for m in c.get("members", [])},
        "profile": load_profile(),
        "knows": build_knows(docs, incoming, data["clusters"]),
        "hubs": sorted(
            ({"stem": d["stem"], "title": d["title"],
              "degree": len(d["links"]) + len(incoming.get(d["stem"], []))}
             for d in docs),
            key=lambda h: -h["degree"])[:8],
        "palette": {
            "accent": "#6C4CF1", "accentDark": "#9B7FF5",
            "bgLight": "#F6F5F1", "bgDark": "#0C0B10",
            "surfaceLight": "#FFFFFF", "surfaceDark": "#16151D",
            "inkLight": "#17141F", "inkDark": "#F4F2FA",
            "mutedLight": "#6F6A7E", "mutedDark": "#A19CB6",
            "warn": "#B45309", "bad": "#C22744",
        },
    }
    payload = json.dumps(brain_json, ensure_ascii=False).replace("</", "<\\/")
    html_text = template_path.read_text(encoding="utf-8")
    html_text = html_text.replace("/*__BRAIN_JSON__*/null", payload)
    return html_text


def _render_dashboard_simple(notes, tag_counts, incoming, broken, orphans, now):
    """Fallback dashboard (no template): stats + tag bars, no JS app."""
    total_links = sum(len(n["links"]) for n in notes)
    max_tag = max(tag_counts.values()) if tag_counts else 1
    recent = sorted(notes, key=lambda n: n["mtime"], reverse=True)[:8]

    def esc(s):
        return html.escape(str(s))

    parts = []
    parts.append("<!DOCTYPE html>")
    parts.append("<html lang=\"en\"><head><meta charset=\"utf-8\">")
    parts.append("<title>Muse Brain — Dashboard</title></head><body>")
    parts.append("<h1>Muse Brain — Dashboard</h1>")
    parts.append(f"<p>Generated by scan.py on {esc(now)}.</p>")
