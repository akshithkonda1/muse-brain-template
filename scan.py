def main() -> int:
    if not NOTES_DIR.is_dir():
        print(f"notes/ not found under {BRAIN}", file=sys.stderr)
        return 1
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    notes = scan_notes()
    tag_counts = Counter()
    for note in notes:
        tag_counts.update(note["tags"])
    incoming, broken, orphans = build_graph(notes)

    MAP_PATH.write_text(
        render_map(notes, tag_counts, incoming, broken, orphans, now),
        encoding="utf-8",
    )
    DASH_PATH.write_text(
        render_dashboard(notes, tag_counts, incoming, broken, orphans, now),
        encoding="utf-8",
    )

    total_links = sum(len(n["links"]) for n in notes)
    print(f"Scanned {len(notes)} notes, {total_links} links.")
    print("Tags: " + ", ".join(
        f"#{t}={tag_counts.get(t, 0)}" for t in CANONICAL_TAGS
    ))
    non_canonical = sorted(t for t in tag_counts if t not in CANONICAL_TAGS)
    if non_canonical:
        print("Non-canonical tags found: " +
              ", ".join(f"#{t}" for t in non_canonical))
    print(f"Broken links: {len(broken)}; orphans: {len(orphans)}.")
    if broken:
        for source, target in broken:
            print(f"  BROKEN: {source} -> [[{target}]]")
    if orphans:
        for stem in orphans:
            print(f"  ORPHAN: {stem}")
    print(f"Wrote {MAP_PATH.name} and {DASH_PATH.name}.")
    return 0


